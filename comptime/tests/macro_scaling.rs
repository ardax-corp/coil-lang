//! Macro expansion grows about linearly with the number of calls in a file
//! (coil-lang#1398), and diagnostics in generated code keep their places.
//!
//! Each macro output used to be parsed behind padding as long as the file
//! plus every earlier output, and each call was found by walking the whole
//! tree, so 8x the calls took far more than 8x the time.

use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use compiler::Pipeline;

/// A project dir with provider `gen.hy`; returns its `src` dir.
fn project(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("coil_macro_scaling_{name}_{}", std::process::id()));
    let src = dir.join("src");
    std::fs::create_dir_all(&src).unwrap();
    std::fs::write(
        src.join("gen.hy"),
        "use macro::{Expr, Code};\n\n\
         macro check(Expr e) -> Code {\n    return quote stmts {\n        if true != ${e} {\n            raise \"failed\";\n        }\n    };\n}\n\n\
         macro mistyped(Expr e) -> Code {\n    return quote stmts {\n        let a = 1;\n        let n: int = ${e};\n    };\n}\n",
    )
    .unwrap();
    src
}

fn pipeline_for(src: &Path) -> Pipeline {
    let mut pipeline = Pipeline::new();
    pipeline.bind_project_root(src.parent().unwrap().to_path_buf(), vec!["src".into()]);
    pipeline
}

/// `main` with `n` `check!` calls among longer statements: the old cost of
/// a call grew with everything before it in the file.
fn many_calls(n: usize) -> String {
    let filler = "text ".repeat(100);
    let mut text = String::from("use gen::{check};\n\nfn main() {\n    let x = 1;\n");
    for i in 0..n {
        text.push_str(&format!("    let s{i} = \"{filler}\";\n    check!(x == 1);\n"));
    }
    text.push_str("}\n");
    text
}

/// Fastest of three expansions of `n` calls.
fn expand_time(src: &Path, n: usize) -> Duration {
    let file = src.join(format!("main{n}.hy"));
    std::fs::write(&file, many_calls(n)).unwrap();
    (0..3)
        .map(|_| {
            let mut pipeline = pipeline_for(src);
            let start = Instant::now();
            let out = pipeline.expanded_source(file.to_str().unwrap()).expect("expands");
            let took = start.elapsed();
            assert!(!out.contains("check!"), "calls left after expansion:\n{out}");
            took
        })
        .min()
        .unwrap()
}

#[test]
fn macro_expansion_is_about_linear_in_calls() {
    comptime::install();
    let src = project("linear");
    // Compile the expansion program once, outside the timing.
    expand_time(&src, 1);
    let small = expand_time(&src, 100);
    let large = expand_time(&src, 800);
    // Linear is ~8x; the old quadratic parse and lookups made it ~35x (debug build).
    let ratio = large.as_secs_f64() / small.as_secs_f64().max(1e-6);
    assert!(ratio < 16.0, "800 calls took {large:?}, 100 took {small:?} ({ratio:.1}x)");
}

#[test]
fn generated_code_diagnostics_keep_their_place() {
    comptime::install();
    let src = project("diag");
    // Earlier outputs move where later ones land in the report text.
    let main = "use gen::{check, mistyped};\n\nfn main() {\n    let x = 1;\n    check!(x == 1);\n    check!(x == 1);\n    mistyped!(\"text\");\n    check!(x == 1);\n}\n";
    let file = src.join("main.hy");
    std::fs::write(&file, main).unwrap();
    let mut pipeline = pipeline_for(&src);
    let errors: Vec<_> = pipeline
        .typecheck_project(&file)
        .into_iter()
        .flat_map(|(_, msgs)| msgs)
        .filter(|m| matches!(m.kind(), reporting::MessageKind::ERROR))
        .collect();
    assert_eq!(errors.len(), 1, "{errors:?}");
    let err = &errors[0];
    let call = main.find("mistyped!").unwrap();
    assert_eq!(*err.range(), call..call + "mistyped!(\"text\")".len(), "{err:?}");
    let help = err.help().clone().unwrap_or_default();
    assert!(
        help.ends_with("in code generated by macro `mistyped!`: `let n__m: int = \"text\";`"),
        "{err:?}"
    );
}
